import type { RouteRecordStringComponent } from '@vben/types';

function page(
  name: string,
  path: string,
  component: string,
  title: string,
  icon: string,
  order: number,
  badge?: string,
): RouteRecordStringComponent {
  return {
    name,
    path,
    component,
    meta: {
      ...(badge
        ? { badge, badgeType: 'normal' as const, badgeVariants: 'primary' }
        : {}),
      icon,
      order,
      title,
    },
  };
}

function group(
  name: string,
  path: string,
  redirect: string,
  title: string,
  icon: string,
  order: number,
  children: RouteRecordStringComponent[],
): RouteRecordStringComponent {
  return {
    name,
    path,
    component: 'BasicLayout',
    redirect,
    meta: { icon, order, title },
    children,
  };
}

function nestedGroup(
  name: string,
  path: string,
  redirect: string,
  title: string,
  icon: string,
  order: number,
  children: RouteRecordStringComponent[],
): RouteRecordStringComponent {
  return {
    name,
    path,
    redirect,
    meta: { icon, order, title },
    children,
  };
}

/** 移除二级及更深目录的BasicLayout，避免嵌套布局破坏标签页切换。 */
export function normalizeNestedLayoutComponents(
  menus: RouteRecordStringComponent[],
  depth = 0,
): void {
  for (const menu of menus) {
    if (
      depth > 0 &&
      menu.children?.length &&
      menu.component === 'BasicLayout'
    ) {
      delete menu.component;
    }
    if (menu.children?.length) {
      normalizeNestedLayoutComponents(menu.children, depth + 1);
    }
  }
}

function hiddenPage(
  name: string,
  path: string,
  component: string,
  title: string,
  activePath?: string,
): RouteRecordStringComponent {
  return {
    name,
    path,
    component,
    meta: {
      ...(activePath ? { activePath } : {}),
      hideInMenu: true,
      title,
    },
  };
}

