    relation_row.region_name = COALESCE(catalog.region_name, '未分类'),
    relation_row.region_value = COALESCE(catalog.country_code, UPPER(relation_row.region_value)),
    relation_row.country_name = COALESCE(catalog.country_name, relation_row.region_value);

