    account_id VARCHAR(64) NOT NULL COMMENT '广告账户ID',
    account_name VARCHAR(255) NULL COMMENT '账户名称',
    account_type VARCHAR(15) NOT NULL DEFAULT '未分类' COMMENT '账户类型名称快照',
    fb_account_id VARCHAR(64) NULL COMMENT 'Facebook账户ID',
