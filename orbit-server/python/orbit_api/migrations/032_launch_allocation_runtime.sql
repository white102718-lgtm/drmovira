-- 投放分配独立持久运行时；不修改021，不创建或冒充公共Task。
CREATE TABLE orbit_launch_allocation_runtime (
 tenant_id CHAR(36) NOT NULL COMMENT '可信会话租户UUID，所有外键显式同租户',
 allocation_id CHAR(36) NOT NULL COMMENT '021真实分配UUID，不是公共Task ID',
 plan_id CHAR(36) NOT NULL COMMENT '所属真实计划UUID，写入时复核021分配归属',
 actor_id BIGINT NOT NULL COMMENT '原受理操作者，领取与发布重新核当前授权',
 producer_kind VARCHAR(16) NOT NULL COMMENT 'TRUSTED可信生产包或ISOLATED_TEST专属测试库包',
 phase VARCHAR(16) NOT NULL COMMENT 'CAPTURED、QUEUED、SOLVING、PUBLISHING、COMPLETE、FAILED内部阶段',
 input_schema_version INT UNSIGNED NOT NULL COMMENT '内部冻结输入编码版本，当前1',
 plan_input_hash CHAR(64) NOT NULL COMMENT '完整规范计划内容摘要，配置变化必须拒绝旧输入',
 source_hash CHAR(64) NOT NULL COMMENT '可信平台能力及选定身份媒体来源完整摘要',
 authority_fingerprint CHAR(64) NOT NULL COMMENT '调用者与实际拥有者授权及范围证据摘要',
 capability_version VARCHAR(64) NOT NULL COMMENT '真实锁定能力包版本，不等于任意浏览器字符串',
 manifest_hash CHAR(64) NOT NULL COMMENT '有序分块序号字节数及摘要的规范清单哈希',
 document_hash CHAR(64) NOT NULL COMMENT '全部分块连接后规范UTF8文档SHA256',
 chunk_count INT UNSIGNED NOT NULL COMMENT '完整冻结块数量，1至256，缺块不可排队',
 byte_total INT UNSIGNED NOT NULL COMMENT '内部完整冻结文档字节数，上限64MiB，不扩大原配置5MiB',
 slot_count INT UNSIGNED NOT NULL COMMENT '完整广告slot数，1至10000',
 previous_allocation_id CHAR(36) NULL COMMENT '受理时旧活跃分配UUID，发布CAS保持旧结果至成功',
 previous_input_hash CHAR(64) NULL COMMENT '旧活跃分配不可变输入摘要，发布与旧ID一起严格CAS',
 attempt INT UNSIGNED NOT NULL DEFAULT 0 COMMENT '实际领取次数，不表示平台写入次数',
 worker_id CHAR(36) NULL COMMENT '实际领取本作业的内部Worker UUID',
 claim_token CHAR(36) NULL COMMENT '本次领取随机标识，禁止旧领取结果写回',
 claim_generation BIGINT UNSIGNED NOT NULL DEFAULT 0 COMMENT '递增围栏代次，最大安全整数',
 lease_until DATETIME(3) NULL COMMENT '数据库UTC租约截止，过期结果不可发布',
 heartbeat_at DATETIME(3) NULL COMMENT '最近一次有效领取心跳数据库UTC时刻',
 next_attempt_at DATETIME(3) NOT NULL COMMENT '首次排队或安全恢复可领取的数据库UTC时间',
 error_code VARCHAR(64) NULL COMMENT '受控错误枚举，不保存自由异常或平台响应',
 created_at DATETIME(3) NOT NULL COMMENT '真实受理UTC时刻',
 updated_at DATETIME(3) NOT NULL COMMENT '阶段或有效领取变更UTC时刻',
 PRIMARY KEY (tenant_id,allocation_id),
 UNIQUE KEY uk_allocation_runtime_plan (tenant_id,plan_id,allocation_id) COMMENT '计划运行时精确归属供guard同租户复合外键',
 KEY idx_allocation_runtime_queue (phase,next_attempt_at,tenant_id,allocation_id) COMMENT '全局内部队列按阶段时间键集领取，不扫描大文档',
 KEY idx_allocation_runtime_lease (phase,lease_until,tenant_id,allocation_id) COMMENT '租约到期有界恢复并增加围栏代次',
 FOREIGN KEY (tenant_id,allocation_id) REFERENCES orbit_launch_allocation(tenant_id,id),
 FOREIGN KEY (tenant_id,plan_id) REFERENCES orbit_launch_plan(tenant_id,id),
 FOREIGN KEY (tenant_id,previous_allocation_id) REFERENCES orbit_launch_allocation(tenant_id,id),
 CONSTRAINT ck_allocation_runtime_phase CHECK (phase IN ('CAPTURED','QUEUED','SOLVING','PUBLISHING','COMPLETE','FAILED')),
 CONSTRAINT ck_allocation_runtime_producer CHECK (producer_kind IN ('TRUSTED','ISOLATED_TEST')),
 CONSTRAINT ck_allocation_runtime_schema CHECK (input_schema_version=1),
 CONSTRAINT ck_allocation_runtime_chunks CHECK (chunk_count BETWEEN 1 AND 256),
 CONSTRAINT ck_allocation_runtime_bytes CHECK (byte_total BETWEEN 1 AND 67108864),
 CONSTRAINT ck_allocation_runtime_slots CHECK (slot_count BETWEEN 1 AND 10000),
 CONSTRAINT ck_allocation_runtime_previous CHECK ((previous_allocation_id IS NULL AND previous_input_hash IS NULL) OR (previous_allocation_id IS NOT NULL AND previous_input_hash IS NOT NULL)),
 CONSTRAINT ck_allocation_runtime_generation CHECK (claim_generation<=9007199254740991)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_as_cs COMMENT='真实素材分配持久队列与租约围栏，不代表平台投放Task';

CREATE TABLE orbit_launch_allocation_chunk (
 tenant_id CHAR(36) NOT NULL COMMENT '与运行时一致的可信租户UUID',
 allocation_id CHAR(36) NOT NULL COMMENT '真实分配UUID，与运行时同租户关联',
 ordinal INT UNSIGNED NOT NULL COMMENT '完整规范UTF8文档的连续零起分块序号',
 payload MEDIUMBLOB NOT NULL COMMENT '规范文档原始字节片段，可跨UTF8码点，仅完整校验后连接解码',
 payload_hash CHAR(64) NOT NULL COMMENT '该片段原始字节SHA256，篡改或缺块拒绝整份输入',
 byte_size INT UNSIGNED NOT NULL COMMENT '真实片段字节数，1至256KiB',
 created_at DATETIME(3) NOT NULL COMMENT '同事务捕获UTC时刻，未完整不得被Worker领取',
 PRIMARY KEY (tenant_id,allocation_id,ordinal),
 FOREIGN KEY (tenant_id,allocation_id) REFERENCES orbit_launch_allocation_runtime(tenant_id,allocation_id),
 CONSTRAINT ck_allocation_chunk_ordinal CHECK (ordinal<256),
 CONSTRAINT ck_allocation_chunk_bytes CHECK (byte_size BETWEEN 1 AND 262144 AND OCTET_LENGTH(payload)=byte_size)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_as_cs COMMENT='最大64MiB完整冻结输入的有界分块，不储存凭证或部分成功映射';

CREATE TABLE orbit_launch_allocation_guard (
 tenant_id CHAR(36) NOT NULL COMMENT '可信租户UUID',
 plan_id CHAR(36) NOT NULL COMMENT '单计划最多一项尚未终结的求解作业',
 allocation_id CHAR(36) NOT NULL COMMENT '当前真实求解运行时UUID，不改变旧活跃分配',
 generation BIGINT UNSIGNED NOT NULL COMMENT '受理序列及运行时CAS辅助版本，不接受客户端改写',
 updated_at DATETIME(3) NOT NULL COMMENT '创建或替换指针数据库UTC时刻',
 PRIMARY KEY (tenant_id,plan_id),
 FOREIGN KEY (tenant_id,plan_id) REFERENCES orbit_launch_plan(tenant_id,id),
 FOREIGN KEY (tenant_id,plan_id,allocation_id) REFERENCES orbit_launch_allocation_runtime(tenant_id,plan_id,allocation_id),
 CONSTRAINT ck_allocation_guard_generation CHECK (generation BETWEEN 1 AND 9007199254740991)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_as_cs COMMENT='单计划正在求解唯一指针，终态同事务释放并保留全部历史结果';
