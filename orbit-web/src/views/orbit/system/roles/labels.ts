export function permissionMenu(code: string) {
  if (code.startsWith('reports.')) return 'monitor'
  if (code.startsWith('tags.')) return 'assets'
  if (code.startsWith('tasks.') || code.startsWith('templates.')) return 'launch'
  return code.split('.')[0]
}
